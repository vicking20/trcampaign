// Launcher window languages: the 14 languages of the game / Autolog
// (internal/server newsLanguages), chosen from LOCALE in nfsrun-launcher.ini
// (the same value the launcher hands the game). LOCALE empty or "auto": the
// Windows display language. Unknown: English. The log stays in English.

type langID string

const (
	langEN   langID = "en"
	langFR   langID = "fr"
	langDE   langID = "de"
	langES   langID = "es"
	langIT   langID = "it"
	langJA   langID = "ja"
	langRU   langID = "ru"
	langPL   langID = "pl"
	langNL   langID = "nl"
	langPT   langID = "pt"
	langZH   langID = "zh"
	langKO   langID = "ko"
	langCS   langID = "cs"
	langESMX langID = "es-MX"
)

var curLang = langEN

// langFromLocale maps en_US, pt-BR, es_MX, jp, zh_CN, ... to a launcher language.
func langFromLocale(loc string) (langID, bool) {
	loc = strings.ToLower(strings.TrimSpace(strings.ReplaceAll(loc, "_", "-")))
	code, region, _ := strings.Cut(loc, "-")
	switch code {
	case "en":
		return langEN, true
	case "fr":
		return langFR, true
	case "de":
		return langDE, true
	case "es":
		// Spain (and unspecified) = Spanish; the Americas = Mexican Spanish
		if region == "" || region == "es" {
			return langES, true
		}
		return langESMX, true
	case "it":
		return langIT, true
	case "ja", "jp":
		return langJA, true
	case "ru":
		return langRU, true
	case "pl":
		return langPL, true
	case "nl":
		return langNL, true
	case "pt":
		return langPT, true
	case "zh":
		return langZH, true
	case "ko", "kr":
		return langKO, true
	case "cs", "cz":
		return langCS, true
	}
	return langEN, false
}

// setLanguage picks the window language from LOCALE (or Windows when empty/auto).
func setLanguage(locale string) {
	if l := strings.TrimSpace(locale); l == "" || strings.EqualFold(l, "auto") {
		locale = systemLocale()
	}
	curLang, _ = langFromLocale(locale)
}

// T returns the text for key in the window language (English when missing).
func T(key string, args ...any) string {
	s, ok := texts[curLang][key]
	if !ok {
		if s, ok = texts[langEN][key]; !ok {
			s = key
		}
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}

