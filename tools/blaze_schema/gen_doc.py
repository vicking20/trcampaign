"""Write docs/BLAZE_API.md from source/internal/blaze/schema.json.

Status per RPC comes from the server test suite:
  cd source && SCHEMA_STATUS_OUT=$PWD/../tools/blaze_schema/status.json go test -run TestEveryCommandAgainstSchema ./internal/server/
"""
import json, os, sys
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
S = json.load(open(os.path.join(root, 'source/internal/blaze/schema.json')))
st_path = os.path.join(root, 'tools/blaze_schema/status.json')
ST = json.load(open(st_path)) if os.path.exists(st_path) else {}
T = S['types']
LABEL = {'implemented': 'yes', 'empty': 'empty reply', 'unimplemented': '—', 'error': 'yes', 'none': '—'}

def short(t):
    return t.replace('Blaze::', '') if isinstance(t, str) else ''

def members(t):
    if not t or t not in T:
        return ''
    return ' '.join(m['tag'] for m in T[t])

out = []
w = out.append
w('# Blaze API of Need for Speed The Run (from the game itself)\n')
w('Generated by `tools/blaze_schema/gen_doc.py` from `source/internal/blaze/schema.json`.')
w('Nothing here comes from other emulators or SDK dumps of other games:\n')
w('* **Ids and names** — the PC exe\'s own getCommandName / getNotificationName switches.')
w('* **Request / response / error types** — the `RpcJob<Response, Error>` each call site of the')
w('  PS3 build constructs, and the request type in the call signature (DWARF).')
w('  `name` = taken from the generated class names because no call site exists (marked *).')
w('* **Members** — the TdfMemberInfo tables (tag, kind, default) + DWARF member names, checked')
w('  against the PC exe\'s tables (712 of 716 identical). NFS-specific types (Autolog, game')
w('  reports) are read from their `visit()` code, PC first.')
w('* **Notifications** — the decoder each `handleNotification` case calls (PS3).\n')
w('How the client decodes (`Heat2Decoder::getHeader`, PS3 `0x012E41C4`): members in ascending tag')
w('order; the same tag with another wire type is a decode error (the rest of the reply is lost);')
w('lower/unknown tags are skipped; a missing member keeps its default. The server now checks every')
w('packet it sends against this schema and logs `[SCHEMA]` lines with `SCHEMA_CHECK=true`.\n')
w('Column *server*: what this server answers — `yes`, `empty reply` (a reply with no members),')
w('`error reply`, `—` (not implemented: an empty success).\n')
comps = {}
for k, v in S['commands'].items():
    comps.setdefault((k[:4], v['component']), []).append((k, v))
for (cid, cname), rows in sorted(comps.items()):
    w(f'## {cname} (component 0x{cid.upper()})\n')
    w('| cmd | name | request | response | error | server |')
    w('|---|---|---|---|---|---|')
    for k, v in sorted(rows):
        rq = short(v.get('request')) + ('*' if v.get('request_confidence') == 'name' else '')
        rs = v.get('response')
        rs = 'void' if rs == 'void' else short(rs) + ('*' if v.get('response_confidence') == 'name' else '')
        er = short(v.get('error'))
        w(f"| 0x{k[5:].upper()} | {v['name']} | {rq} | {rs} | {er} | {LABEL.get(ST.get(k), '?')} |")
    w('')
w('## Notifications\n')
w('| component | id | name | type |')
w('|---|---|---|---|')
for k, v in sorted(S['notifications'].items()):
    w(f"| {v['component']} | 0x{k[5:].upper()} | {v.get('name') or ''} | {short(v.get('type'))} |")
w('')
w('## Types used by the server\n')
used = set()
for k, v in S['commands'].items():
    if ST.get(k) in ('implemented', 'empty', 'error'):
        for t in (v.get('request'), v.get('response'), v.get('error')):
            if isinstance(t, str) and t in T:
                used.add(t)
for v in S['notifications'].values():
    if v.get('type') in T:
        used.add(v['type'])
def walk(t, seen):
    if t in seen or t not in T:
        return
    seen.add(t)
    for m in T[t]:
        for part in m['spec'].replace('list:', '').replace('map:', '').split('|'):
            if part.startswith('struct:'):
                walk(part[7:], seen)
            if part.startswith('union:'):
                for vs in S['unions'].get(part[6:], {}).values():
                    if vs.startswith('struct:'):
                        walk(vs[7:], seen)
allused = set()
for t in sorted(used):
    walk(t, allused)
for t in sorted(allused):
    w(f'### {short(t)}\n')
    w('| tag | member | type | default |')
    w('|---|---|---|---|')
    for m in T[t]:
        d = m.get('default', '')
        w(f"| {m['tag']} | {m['name']} | {short(m['spec'])} | {d} |")
    w('')
open(os.path.join(root, 'docs/BLAZE_API.md'), 'w').write('\n'.join(out) + '\n')
print('docs/BLAZE_API.md:', len(S['commands']), 'RPCs,', len(allused), 'types')
